<?php

namespace App\Models;

use App\Models\Concerns\FlushesLocationCache;
use App\Models\Concerns\HasUuidPrimaryKey;
use Database\Factories\StreetFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

class Street extends Model
{
    /** @use HasFactory<StreetFactory> */
    use FlushesLocationCache, HasFactory, HasUuidPrimaryKey;

    protected $table = 'streets';

    protected $keyType = 'string';

    public $incrementing = false;

    protected $fillable = [
        'id', 'area_id', 'name', 'name_ar', 'name_en',
        'latitude', 'longitude', 'source', 'external_id',
    ];

    /**
     * Generated by the database; never written from PHP.
     */
    protected $hidden = ['name_key', 'search_text'];

    protected function casts(): array
    {
        return [
            'latitude' => 'float',
            'longitude' => 'float',
        ];
    }

    public function area()
    {
        return $this->belongsTo(Area::class);
    }
}
