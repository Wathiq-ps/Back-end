<?php

namespace App\Models;

use App\Models\Concerns\FlushesLocationCache;
use App\Models\Concerns\HasUuidPrimaryKey;
use Database\Factories\CountryFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

/**
 * Top of the location picker. Unlike the levels below it there is no single
 * `name` column: name_en always comes with the import, name_ar may not.
 */
class Country extends Model
{
    /** @use HasFactory<CountryFactory> */
    use FlushesLocationCache, HasFactory, HasUuidPrimaryKey;

    protected $table = 'countries';

    protected $keyType = 'string';

    public $incrementing = false;

    protected $fillable = ['id', 'iso2', 'iso3', 'name_ar', 'name_en', 'dial_code', 'is_supported'];

    /**
     * Generated by the database; never written from PHP.
     */
    protected $hidden = ['search_text'];

    protected function casts(): array
    {
        return ['is_supported' => 'boolean'];
    }

    public function cities()
    {
        return $this->hasMany(City::class);
    }
}
