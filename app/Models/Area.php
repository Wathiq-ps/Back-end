<?php

namespace App\Models;

use App\Models\Concerns\FlushesLocationCache;
use App\Models\Concerns\HasUuidPrimaryKey;
use Database\Factories\AreaFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

/**
 * A district, neighbourhood or quarter inside a city.
 */
class Area extends Model
{
    /** @use HasFactory<AreaFactory> */
    use FlushesLocationCache, HasFactory, HasUuidPrimaryKey;

    protected $table = 'areas';

    protected $keyType = 'string';

    public $incrementing = false;

    protected $fillable = [
        'id', 'city_id', 'name', 'name_ar', 'name_en',
        'latitude', 'longitude', 'source', 'external_id',
    ];

    /**
     * Generated by the database; never written from PHP.
     */
    protected $hidden = ['name_key', 'search_text'];

    protected function casts(): array
    {
        return [
            'latitude' => 'float',
            'longitude' => 'float',
        ];
    }

    public function city()
    {
        return $this->belongsTo(City::class);
    }

    public function streets()
    {
        return $this->hasMany(Street::class);
    }
}
