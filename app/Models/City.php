<?php

namespace App\Models;

use App\Models\Concerns\FlushesLocationCache;
use App\Models\Concerns\HasUuidPrimaryKey;
use Database\Factories\CityFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

class City extends Model
{
    /** @use HasFactory<CityFactory> */
    use FlushesLocationCache, HasFactory, HasUuidPrimaryKey;

    protected $table = 'cities';

    protected $keyType = 'string';

    public $incrementing = false;

    protected $fillable = [
        'id', 'country_id', 'name', 'name_ar', 'name_en',
        'latitude', 'longitude', 'population', 'source', 'external_id',
    ];

    /**
     * Generated by the database; never written from PHP.
     */
    protected $hidden = ['search_text'];

    protected function casts(): array
    {
        return [
            'latitude' => 'float',
            'longitude' => 'float',
            'population' => 'integer',
        ];
    }

    public function country()
    {
        return $this->belongsTo(Country::class);
    }

    public function areas()
    {
        return $this->hasMany(Area::class);
    }
}
